"""Reconcile fresh inventories with saved entries by source geometry, never manual labels."""
import argparse
from collections import Counter
from copy import deepcopy
import hashlib
import json
from pathlib import Path

from folio_capture.export import atomic_write, batch_zip
from folio_capture.manual import complete_capture, manual_sheets
from folio_capture.schema import TYPES


def overlap(a, b, contained=False):
    scores = []
    for ar in a['regions']:
        for br in b['regions']:
            if ar['page'] != br['page']: continue
            x, y, r, d = ar['box']; X, Y, R, D = br['box']
            intersection = max(0, min(r,R)-max(x,X)) * max(0, min(d,D)-max(y,Y))
            area_a, area_b = (r-x)*(d-y), (R-X)*(D-Y)
            denominator = min(area_a,area_b) if contained else area_a+area_b-intersection
            scores.append(intersection/denominator if denominator else 0)
    return max(scores, default=0)


def reconcile(folio, inventory):
    folio = deepcopy(folio)
    original = folio['entries'][:]
    for entry in original:
        entry.pop('inventory_proposals', None)
    parent_counts = Counter(p.get('parent_key') for p in inventory['entries'] if p.get('parent_key'))
    matches = {}
    added = []
    for proposal in inventory['entries']:
        if proposal['entry_type'] not in TYPES: continue
        candidates = [e for e in original if e['entry_type'] == proposal['entry_type']]
        hint = ''.join(proposal.get('new_folio_hint','').upper().split())
        if hint:
            candidates = [e for e in candidates if not e.get('new_folio_hint') or
                          ''.join(e['new_folio_hint'].upper().split()) == hint]
        contained = proposal['entry_type'] == 'Description of Land'
        best = max(candidates, key=lambda e: overlap(e,proposal,contained), default=None)
        # A unique same-page target is stronger identity evidence than crop size.
        same_page_target = hint and len(candidates) == 1 and bool(
            {r['page'] for r in candidates[0]['regions']} & {r['page'] for r in proposal['regions']})
        if best and (overlap(best,proposal,contained) >= (.7 if contained else .25) or same_page_target):
            matches.setdefault(best['id'], []).append(proposal)
        else:
            entry = deepcopy(proposal)
            entry.update(id=hashlib.sha256((folio['source_id']+json.dumps(proposal,sort_keys=True)).encode()).hexdigest()[:24],
                         key='inventory_'+proposal['key'], parent_id=(proposal.get('parent_key','')
                             if parent_counts[proposal.get('parent_key')] > 1 else ''),
                         attributes={}, field_evidence={}, relationships=[], reasons=['FRESH_INVENTORY_ENTRY'],
                         review_status='needs_review', record_kind='entry')
            added.append(entry)
    for entry in original:
        proposals = matches.get(entry['id'], [])
        if not proposals:
            if entry['entry_type'] in TYPES:
                entry.setdefault('reasons', []).append('INVENTORY_NOT_CONFIRMED')
            continue
        entry['prior_inventory'] = {k:deepcopy(entry.get(k)) for k in ('status','regions','page_entry_number')}
        entry['inventory_proposals'] = proposals
        shared_parents = {p['parent_key'] for p in proposals if p.get('parent_key') and parent_counts[p['parent_key']] > 1}
        if len(shared_parents) == 1: entry['parent_id'] = shared_parents.pop()
        statuses = {p['status'] for p in proposals}
        numbers = [p['page_entry_number'] for p in proposals if p.get('page_entry_number') is not None]
        if numbers: entry['page_entry_number'] = min(numbers)
        if len(statuses) == 1:
            entry['status'] = statuses.pop()
        else:
            entry.setdefault('reasons', []).append('INVENTORY_STATUS_DISAGREEMENT')
        entry['regions'] = [r for p in proposals for r in p['regions']]
        if entry['prior_inventory']['status'] and not entry['status']:
            entry['attributes'] = {}
            entry['field_evidence'] = {}
            entry['relationships'] = []
            entry.setdefault('reasons', []).append('FRESH_INVENTORY_RECOVERED')
    folio['entries'].extend(added)
    folio['inventory_notes'] = inventory['notes']
    return folio


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--baseline', type=Path, required=True)
    parser.add_argument('--inventory', type=Path, default=Path('output/manual-v2-inventory'))
    parser.add_argument('--output', type=Path, default=Path('output/manual-v2-recovered'))
    parser.add_argument('--captures', type=Path, help='Overlay saved extraction results by immutable entry ID')
    parser.add_argument('--fresh-captures-only', action='store_true', help='Overlay only results generated by the capture run itself')
    limited = parser.add_mutually_exclusive_group()
    limited.add_argument('--numbers-only', action='store_true', help='Update page entry numbers without changing extraction or inventory membership')
    limited.add_argument('--regions-only', action='store_true', help='Update matched source regions without changing extraction, numbering or inventory membership')
    args = parser.parse_args()
    capture_fingerprint = (json.loads((args.captures/'manifest.json').read_text())['experiment_fingerprint']
                           if args.fresh_captures_only else None)
    folios = []
    for path in sorted(args.baseline.glob('*-evidence.json')):
        folio = json.loads(path.read_text())
        inventory_path = args.inventory/(folio['source_id']+'-inventory.json')
        if inventory_path.exists():
            inventory = json.loads(inventory_path.read_text())['inventory']
            updated = reconcile(folio, inventory)
            if args.numbers_only or args.regions_only:
                by_id = {e['id']:e for e in updated['entries']}
                for entry in folio['entries']:
                    update = by_id[entry['id']]
                    if args.regions_only and update.get('inventory_proposals'):
                        entry['regions'] = update['regions']
                        entry['region_proposals'] = update['inventory_proposals']
                    elif args.numbers_only and update.get('inventory_proposals') and update.get('page_entry_number') is not None:
                        entry['page_entry_number'] = update['page_entry_number']
                        entry['numbering_proposals'] = update['inventory_proposals']
            else:
                folio = updated
        elif not (args.numbers_only or args.regions_only):
            raise FileNotFoundError(inventory_path)
        if args.captures:
            captures=json.loads((args.captures/path.name).read_text())
            by_id={e['id']:e for e in captures['entries']}
            for entry in folio['entries']:
                captured=by_id.get(entry['id'], {})
                if capture_fingerprint and captured.get('experiment_fingerprint') != capture_fingerprint: continue
                if captured.get('attributes') and not captured.get('status'):
                    for field in ('attributes','field_evidence','relationships','extraction_notes',
                                  'experiment_model','experiment_fingerprint','experiment_usage','capture_profile'):
                        if field in captured: entry[field]=deepcopy(captured[field])
                    entry['reasons']=list(dict.fromkeys(entry.get('reasons',[])+captured.get('reasons',[])))
                    if 'ENTRY_EXTRACTION_FAILED' not in captured.get('reasons',[]):
                        entry['reasons']=[r for r in entry['reasons'] if r!='ENTRY_EXTRACTION_FAILED']
        if not (args.numbers_only or args.regions_only):
            for entry in folio['entries']: complete_capture(entry,folio['source_id'])
        folios.append(folio)
        atomic_write(args.output/path.name, json.dumps(folio,ensure_ascii=False).encode())
    manifest = {'baseline':str(args.baseline), 'inventory':str(args.inventory),
                'captures':str(args.captures) if args.captures else None, 'numbers_only':args.numbers_only,
                'regions_only':args.regions_only, 'review_required':True}
    atomic_write(args.output/'current.zip', batch_zip(folios,manifest))
    atomic_write(args.output/'manual_sheets.json', json.dumps(manual_sheets(folios),ensure_ascii=False).encode())
    print('RECONCILED',len(folios),'folios')


if __name__ == '__main__': main()
